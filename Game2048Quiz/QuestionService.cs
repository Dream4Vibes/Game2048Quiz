                // Давайте вернем null и обработаем это в игре
                return null;
            }

            int index = random.Next(_currentGameQuestions.Count);
            Question q = _currentGameQuestions[index];

            // Удаляем вопрос, чтобы он больше не попался
            _currentGameQuestions.RemoveAt(index);

            return q;
        }

